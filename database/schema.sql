-- Visão de consulta compatível com instalações anteriores; a API calcula via EF.
BEGIN;
CREATE OR REPLACE VIEW produto_com_estoque AS
SELECT p.codprod, p.nome_produto, p.preco, p.descricao, p.categoria,
       p.status_disponibilidade, p.imagem_url, p.eh_kit,
       CASE WHEN p.eh_kit THEN COALESCE((
           SELECT min(CASE WHEN c.eh_kit OR c.status_disponibilidade <> 'disponivel'
                           THEN 0 ELSE c.estoque / k.quantidade END)
           FROM kit_componente k JOIN produto c ON c.codprod = k.id_produto
           WHERE k.id_kit = p.codprod
       ), 0)::int ELSE p.estoque END AS estoque
FROM produto p;
COMMIT;
